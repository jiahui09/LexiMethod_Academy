/** 音标离线音频 URL；无映射返回 null（调用方回退浏览器 TTS） */
export function phonemeAudioUrl(id: string): string | null {
  const slug = PHONEME_AUDIO[id];
  return slug ? `${import.meta.env.BASE_URL}audio/phonemes/${slug}.mp3` : null;
}

