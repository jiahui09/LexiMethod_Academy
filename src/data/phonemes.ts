import type { Phoneme, Articulation, MinimalPair } from '@/types';

/**
 * 48 个音标（12 单元音 + 8 双元音 + 28 辅音）
 * geo 参数驱动口腔侧视 SVG 动画（0~1 归一化）。
 */

/** 元音几何 */
const vow = (
  tongueHigh: number,
  tongueFront: number,
  lipRound: number,
  jawOpen: number,
  place: Articulation['place'],
): Articulation => ({ tongueHigh, tongueFront, lipRound, jawOpen, manner: 'vowel', place });

/** 辅音几何 */
const cons = (
  place: Articulation['place'],
  manner: Articulation['manner'],
  closure: number,
  extra: Partial<Articulation> = {},
): Articulation => ({
  tongueHigh: manner === 'fricative' || manner === 'sibilant' ? 0.72 : 0.5,
  tongueFront: place === 'alveolar' || place === 'dental' ? 0.78 : place === 'velar' || place === 'glottal' ? 0.2 : 0.5,
  lipRound: place === 'bilabial' && manner !== 'nasal' ? 0.55 : 0.2,
  jawOpen: manner === 'plosive' ? 0.22 : manner === 'affricate' ? 0.25 : 0.35,
  manner,
  place,
  closure,
  ...extra,
});

const P = (a: string, b: string, meaningA: string, meaningB: string): MinimalPair => ({ a, b, meaningA, meaningB });

